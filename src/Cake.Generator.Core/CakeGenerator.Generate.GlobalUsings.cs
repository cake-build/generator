namespace Cake.Generator;

public partial class CakeGenerator
{
    private static string GenerateGlobalUsings(List<MethodInfo> methods)
    {
        var excludedNamespaces = new HashSet<string>(StringComparer.Ordinal)
        {
            "Cake.Common.Build", // Exclude Cake.Common.Build to avoid conflicts with BuildSystem property and class.
            // Importing this namespace would collide with the Cake.Common ServiceProvider alias.
            "Microsoft.Extensions.DependencyInjection"
        };

        var foundNamespaces = new HashSet<string>(StringComparer.Ordinal)
        {
            "System",
            "System.Collections.Generic",
            "System.Collections.Concurrent",
            "System.Linq",
            "System.Text",
            "System.Text.Json",
            "System.Threading.Tasks",
            "System.IO",
            "Cake.Core",
            "Cake.Core.Configuration",
            "Cake.Core.Diagnostics",
            "Cake.Core.IO",
            "Cake.Core.IO.NuGet",
            "Cake.Core.Reflection",
            "Cake.Core.Scripting",
            "Cake.Core.Tooling",
            "Cake.Cli",
            "Spectre.Console"
        };

        // Get unique assembly names from methods to generate static usings
        var assemblyNames = new HashSet<string>();
        var aliasNames = new HashSet<string>(StringComparer.Ordinal);
        var aliasContainingTypes = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        var excludedAliasNamespaces = new Dictionary<string, INamespaceSymbol>(StringComparer.Ordinal);
        foreach (var method in methods)
        {
            var assemblyName = method.Symbol.ContainingAssembly.Name;
            assemblyNames.Add(assemblyName);
            aliasNames.Add(method.Symbol.Name);
            aliasContainingTypes.Add(method.Symbol.ContainingType);

            var containingNamespace = method.Symbol.ContainingNamespace.ToDisplayString();
            foundNamespaces.Add(containingNamespace);
            if (excludedNamespaces.Contains(containingNamespace))
            {
                excludedAliasNamespaces[containingNamespace] = method.Symbol.ContainingNamespace;
            }

            // Add namespaces from CakeNamespaceImportAttribute
            foreach (var namespaceImport in method.NamespaceImports)
            {
                foundNamespaces.Add(namespaceImport);
            }
        }

        using var sb = StringBuilderCache.Acquire();
        sb.StringBuilder.AppendLine("// <auto-generated/>");
        sb.StringBuilder.AppendLine("// Global usings for all Cake method aliases");
        sb.StringBuilder.AppendLine();

        // Add regular global usings
        var globalUsings = string.Join(
                                "\n",
                                foundNamespaces
                                    .Except(excludedNamespaces)
                                    .OrderBy(x => x)
                                    .Select(ns => $"global using global::{ns};"));
        sb.StringBuilder.AppendLine(globalUsings);
        sb.StringBuilder.AppendLine();

        // Alias the types of excluded alias namespaces that don't collide with an alias (i.e. BuildProvider but not BuildSystem)
        var typeAliases = excludedAliasNamespaces
                            .OrderBy(x => x.Key, StringComparer.Ordinal)
                            .SelectMany(x => x.Value
                                .GetTypeMembers()
                                .Where(type => type.DeclaredAccessibility == Accessibility.Public
                                            && type.Arity == 0
                                            && !aliasNames.Contains(type.Name)
                                            && !aliasContainingTypes.Contains(type))
                                .OrderBy(type => type.Name, StringComparer.Ordinal)
                                .Select(type => $"global using {type.Name} = global::{x.Key}.{type.Name};"))
                            .ToArray();
        if (typeAliases.Length > 0)
        {
            sb.StringBuilder.AppendLine(string.Join("\n", typeAliases));
            sb.StringBuilder.AppendLine();
        }

        sb.StringBuilder.AppendLine("global using IServiceCollection = global::Microsoft.Extensions.DependencyInjection.IServiceCollection;");
        sb.StringBuilder.AppendLine("global using ServiceCollection = global::Microsoft.Extensions.DependencyInjection.ServiceCollection;");
        sb.StringBuilder.AppendLine("global using static global::Microsoft.Extensions.DependencyInjection.ServiceCollectionContainerBuilderExtensions;");
        sb.StringBuilder.AppendLine("global using static global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions;");
        sb.StringBuilder.AppendLine("global using static global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions;");
        sb.StringBuilder.AppendLine();

        sb.StringBuilder.AppendLine($"global using static global::Program;");

        // Add global static usings for generated flat classes
        sb.StringBuilder.AppendLine("// Global static usings for generated Cake alias classes");
        foreach (var assemblyName in assemblyNames.OrderBy(x => x))
        {
            var flatClassName = GetAssemblyClassName(assemblyName);
            sb.StringBuilder.AppendLine($"global using static global::Program.{flatClassName};");
        }

        return sb.StringBuilder.ToString();
    }
}
